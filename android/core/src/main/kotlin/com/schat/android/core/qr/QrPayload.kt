package com.schat.android.core.qr

/**
 * What a SCHAT QR code can carry.
 *
 * # Why the payload is a URI rather than raw hex
 *
 * The obvious encoding for "my identity" is the 64 hex characters themselves, and a bare
 * hex string IS accepted on scan so that any generator produces something usable. But a
 * URI carries a type, which matters as soon as there is more than one thing worth
 * scanning: a server connection URI and a peer identity look nothing alike, and without a
 * scheme the code would have to guess from shape. Guessing wrong means trying to dial a
 * peer identity as a server, and the resulting error would be nonsense to the user.
 *
 * # What a QR code does and does not prove
 *
 * It proves nothing. Scanning the other device's own screen is exactly as trustworthy as
 * copy-pasting the same characters — both transfer whatever that device chose to show.
 * It removes transcription errors, which is a real gain (a single mistyped hex character
 * produces the same "no bundle published" error as a peer that never published), but the
 * actual authentication is still the out-of-band comparison of the safety number. Nothing
 * in the UI may suggest otherwise.
 */
sealed interface QrPayload {

    /** A peer's identity signing public key, lowercase hex. */
    data class Identity(val identityHex: String) : QrPayload

    /** A relay connection URI, unvalidated: [com.schat.android.core.ServerConfig] owns that. */
    data class ServerConfig(val uri: String) : QrPayload

    companion object {

        /** The URI scheme both payload kinds share. */
        const val SCHEME = "schat"

        /** Host part of an identity payload. */
        const val IDENTITY_HOST = "id"

        /** Host part of a connection payload, shared with the server's printed URI. */
        const val CONNECT_HOST = "connect"

        /** Length of an identity signing public key, hex. */
        const val IDENTITY_HEX_LENGTH = 64

        private val HEX = Regex("^[0-9a-fA-F]+$")

        /**
         * Renders the payload for an identity.
         *
         * The identity is what the peer's device shows under "my complete identity"; the
         * relay's own directory key is the same string, so one payload serves both.
         */
        fun identity(identityHex: String): String =
            "$SCHEME://$IDENTITY_HOST?i=${identityHex.trim().lowercase()}"

        /**
         * Renders the payload for a relay connection URI.
         *
         * It is passed through unchanged: the server already prints a `schat://connect?...`
         * URI, and re-encoding it here would create a second definition of that format that
         * could drift from the one the server writes.
         */
        fun serverConfig(uri: String): String = uri.trim()

        /**
         * Interprets whatever a scanner produced, or null when it is not a SCHAT payload.
         *
         * Returning null rather than throwing is deliberate: a scanner pointed at a random
         * QR code on a poster is an ordinary event, not an error worth a stack trace.
         */
        fun parse(text: String?): QrPayload? {
            if (text == null) return null

            // Scanners routinely include a trailing newline, and camera-decode paths have
            // been known to include other whitespace. Trimming first is what keeps a
            // payload that "looks right on screen" from failing for an invisible reason.
            val trimmed = text.trim().trim('\u0000')
            if (trimmed.isEmpty()) return null

            val lower = trimmed.lowercase()

            // A bare identity is accepted so that a QR generated by some other tool — or a
            // future version with a different scheme — still works.
            if (trimmed.length == IDENTITY_HEX_LENGTH && HEX.matches(trimmed)) {
                return QrPayload.Identity(lower)
            }

            if (!lower.startsWith("$SCHEME://")) return null

            val withoutScheme = lower.removePrefix("$SCHEME://")
            val host = withoutScheme.substringBefore('?').substringBefore('/')

            return when (host) {
                IDENTITY_HOST -> identityFromQuery(withoutScheme)
                CONNECT_HOST -> QrPayload.ServerConfig(trimmed)
                else -> null
            }
        }

        /** Extracts `i=` from an identity payload's query string. */
        private fun identityFromQuery(withoutScheme: String): QrPayload? {
            val query = withoutScheme.substringAfter('?', "")
            if (query.isEmpty()) return null

            for (pair in query.split('&')) {
                val key = pair.substringBefore('=', "")
                if (key != "i") continue

                val value = pair.substringAfter('=', "").trim()
                if (value.length != IDENTITY_HEX_LENGTH || !HEX.matches(value)) return null
                return QrPayload.Identity(value.lowercase())
            }
            return null
        }
    }
}
